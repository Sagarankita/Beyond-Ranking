def file_sha256(path: Path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def summarize_columns(frame: pd.DataFrame, schema):
    specs = schema.field_map
    records = []
    for name in frame.columns:
        series = frame[name]
        record = {
            "column": name,
            "role": specs[name].role if name in specs else "undefined",
            "unit": specs[name].unit if name in specs else "undefined",
            "dtype": str(series.dtype),
            "rows": len(series),
            "missing": int(series.isna().sum()),
            "unique": int(series.nunique(dropna=True)),
            "minimum": None,
            "maximum": None,
            "mean": None,
            "standard_deviation": None,
        }
        numeric = pd.to_numeric(series, errors="coerce")
        finite = numeric[np.isfinite(numeric)]
        if not finite.empty and len(finite) == int(series.notna().sum()):
            record.update(
                minimum=float(finite.min()),
                maximum=float(finite.max()),
                mean=float(finite.mean()),
                standard_deviation=float(finite.std()) if len(finite) > 1 else 0.0,
            )
        records.append(record)
    return pd.DataFrame(records)


def verify_legacy_generator(frame: pd.DataFrame):
    if len(frame) != 521:
        return {"checked": False, "value_match": False, "reason": "row count is not 521"}
    expected = generate_legacy_synthetic(n_records=521, seed=42, include_metadata=False)
    if list(frame.columns) != list(expected.columns):
        return {"checked": True, "value_match": False, "reason": "columns differ"}
    mismatches = []
    maximum_absolute_difference = 0.0
    for column in frame.columns:
        if pd.api.types.is_numeric_dtype(expected[column]):
            actual_values = pd.to_numeric(frame[column], errors="coerce").to_numpy(dtype=float)
            expected_values = expected[column].to_numpy(dtype=float)
            difference = np.abs(actual_values - expected_values)
            maximum_absolute_difference = max(
                maximum_absolute_difference,
                float(np.nanmax(difference)) if len(difference) else 0.0,
            )
            # CSV decimal round-tripping can differ by one floating-point ULP at
            # large budget magnitudes; require machine-precision relative agreement.
            if not np.allclose(actual_values, expected_values, rtol=1e-15, atol=1e-12, equal_nan=True):
                mismatches.append(column)
        elif not frame[column].equals(expected[column]):
            mismatches.append(column)
    return {
        "checked": True,
        "value_match": not mismatches,
        "seed": 42,
        "generator_version": "legacy-research-v1",
        "mismatched_columns": mismatches,
        "maximum_absolute_difference": maximum_absolute_difference,
    }


def audit_dataset(
    input_path: Path,
    output_dir: Path,
    schema_name: str,
    scenario_path: Path | None = None,
    bounds_path: Path | None = None,
):
    frame = pd.read_csv(input_path)
    schema = get_schema(schema_name)
    bounds = None
    if bounds_path:
        bounds = json.loads(bounds_path.read_text())["bounds"]
    source_before = frame.copy(deep=True)
    validation = validate_dataframe(frame, schema, scenario_bounds=bounds)
    pd.testing.assert_frame_equal(frame, source_before)

    scenario_validation = None
    if scenario_path:
        scenario_validation = validate_scenario_config(load_scenario(scenario_path)).to_dict()
    generator_verification = (
        verify_legacy_generator(frame)
        if schema_name == "legacy_synthetic_research"
        else {"checked": False, "reason": "not the legacy generator schema"}
    )
    summary = summarize_columns(frame, schema)
    audit = {
        "input": str(input_path),
        "sha256": file_sha256(input_path),
        "rows": len(frame),
        "columns": len(frame.columns),
        "schema": schema_name,
        "provenance_classification": (
            "synthetic" if schema_name == "legacy_synthetic_research" else "declared_per_record"
        ),
        "source_data_mutated": False,
        "validation": validation.to_dict(),
        "generator_verification": generator_verification,
        "scenario_config": str(scenario_path) if scenario_path else None,
        "scenario_validation": scenario_validation,
        "objective_inventory": OBJECTIVE_INVENTORY,
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "audit.json").write_text(json.dumps(audit, indent=2) + "\n")
    summary.to_csv(output_dir / "column_summary.csv", index=False)
    pd.DataFrame([issue.to_dict() for issue in validation.issues]).to_csv(
        output_dir / "validation_issues.csv", index=False
    )
    pd.DataFrame(OBJECTIVE_INVENTORY).to_csv(
        output_dir / "objective_inventory.csv", index=False
    )
    (output_dir / "data_dictionary.json").write_text(
        json.dumps(data_dictionary(), indent=2) + "\n"
    )
    return audit


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", default="data/department_research_data.csv")
    parser.add_argument("--schema", default="legacy_synthetic_research")
    parser.add_argument("--output-dir", default="artifacts/data_audit/legacy_synthetic")
    parser.add_argument(
        "--scenario", default="configs/scenarios/baseline.synthetic.json"
    )
    parser.add_argument(
        "--bounds", default="configs/legacy_optimizer_bounds.json"
    )
    return parser.parse_args()


def main():
    args = parse_args()
    audit = audit_dataset(
        Path(args.input),
        Path(args.output_dir),
        args.schema,
        Path(args.scenario) if args.scenario else None,
        Path(args.bounds) if args.bounds else None,
    )
    counts = audit["validation"]["issue_counts"]
    print(
        f"Audited {audit['rows']} rows with schema {audit['schema']}: "
        f"{counts['error']} errors, {counts['warning']} warnings"
    )
    print(f"Generator value match: {audit['generator_verification'].get('value_match')}")
    print(f"Source data mutated: {audit['source_data_mutated']}")


if __name__ == "__main__":
    main()
